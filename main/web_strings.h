/* One pair, picked by language. webserver.c wraps this as T(). */
const char *web_str(str_id_t id, lang_t lang);

/* Time32 counts TAI seconds from 2004-01-01 00:00:00 UTC, and five leap seconds have been
 * inserted since then, so the same moment in UTC lies that much earlier. A value of 0 means
 * no time at all and converts to 0, which no caller may print as a date. */
uint64_t web_time32_to_unix(uint32_t time32);

/* The other way round, for a question the firmware asks in Time32 seconds. Returns 0 when
 * the unix second lies before the Time32 epoch, which no set clock does. */
uint32_t web_unix_to_time32(uint64_t unix_seconds);

/* Whether a wall clock reading may be used to judge a date. Everything below the threshold
 * is the unset clock of a device that has not reached an NTP server yet. */
bool web_clock_set(uint32_t unix_seconds);

/* Both date orders take ten characters, and the rest is headroom for a far future year. */
#define WEB_DAY_MAX 16

/* The day of a Time32 in local time, written the way the language writes dates. `out` always
 * comes back terminated, and empty for a Time32 of 0, which is no time at all. */
void web_day_str(uint32_t time32, lang_t lang, char *out, size_t cap);
